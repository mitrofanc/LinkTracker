CREATE TABLE sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL,
    canonical_url TEXT NOT NULL,
    external_id TEXT NOT NULL,
    CONSTRAINT ck_sources_type CHECK (type IN ('GITHUB')),
    CONSTRAINT ck_sources_canonical_url CHECK (
        canonical_url <> '' AND canonical_url = btrim(canonical_url)
    ),
    CONSTRAINT ck_sources_external_id CHECK (
        external_id <> '' AND external_id = lower(btrim(external_id))
    ),
    CONSTRAINT uq_sources_canonical_url UNIQUE (canonical_url),
    CONSTRAINT uq_sources_type_external_id UNIQUE (type, external_id)
);

